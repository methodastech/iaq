/* 29 Sep 2026: the Design tab's isometric objects for the booth artwork, Direction B.
   Reads public/design/iso (three service objects, still versions, and six fab systems) and writes
   src/assets/booth/iso-set-0929.js: each drawing's inner markup with its class styles moved inline (inline SVG
   <style> is global to the page and the files reuse the same class names, so every class and id is prefixed), and the
   screen-only non-scaling stroke taken off so the lines scale with the piece and print at 1:1 on a wall.
   Stroke widths read calc(var(--isw,1) * N px), so a piece can thicken them (--isw on the wrapper).
   Usage: node tools/booth-iso-0929.mjs */
import fs from 'node:fs'
const SRC = 'public/design/iso', OUT = 'src/assets/booth/iso-set-0929.js'
const SET = {
  /* the three units' objects (EPC builds, PCU & TTI hooks up, EFM maintains); the other service objects are left out to
     keep the module light, add them here if a piece needs them */
  construct: 'svc-construct-still', maintain: 'svc-maintain-still', hookup: 'svc-hookup-still',
  cleanroom: 'cleanroom', utilities: 'process-utilities', air: 'air-conditioning', electrical: 'electrical',
  fire: 'fire-protection', building: 'overall',
}
/* 30 Sep: the conversion is a function, so the Direction C set (below) goes through the same steps */
function conv(k, s, recolour) {
  const vb = s.match(/viewBox="([^"]+)"/)[1]
  const css = (s.match(/<style>([^<]*)<\/style>/) || [, ''])[1]
  const rules = {}
  for (const [, sel, body] of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const name = sel.trim()
    if (!name.startsWith('.')) continue
    rules[name.slice(1)] = body.split(';').filter(Boolean).map(d => {
      const [p, v] = d.split(':').map(x => x.trim())
      if (p === 'vector-effect') return ''
      if (p === 'stroke-width') return `stroke-width:calc(var(--isw,1) * ${parseFloat(v)}px)`
      if (recolour && (p === 'fill' || p === 'stroke') && v !== 'none') return `${p}:${recolour(p, v)}`
      return `${p}:${v}`
    }).filter(Boolean).join(';')
  }
  let inner = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<style>[^<]*<\/style>/, '')
  inner = inner.replace(/class="([^"]+)"/g, (_, c) => `class="${c.split(/\s+/).map(x => `bi-${k}-${x}`).join(' ')}"`)
  const style = Object.entries(rules).map(([c, b]) => `.bi-${k}-${c}{${b}}`).join('')
  inner = inner.replace(/id="([^"]+)"/g, `id="bi-${k}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#bi-${k}-$1)`)
  inner = `<style>${style}</style><g stroke-linejoin="round" stroke-linecap="round">${inner}</g>`
  return { vb, inner }
}
const out = {}
for (const [k, f] of Object.entries(SET)) out[k] = conv(k, fs.readFileSync(`${SRC}/${f}.svg`, 'utf8'))
const js = `/* generated by tools/booth-iso-0929.mjs from public/design/iso (29 Sep 2026): the Design tab's isometric objects,
   classes prefixed, strokes scaled with the piece. Do not edit by hand: rerun the tool. */
export const ISO_SET = ${JSON.stringify(out)}\n`
fs.writeFileSync(OUT, js)
console.log(OUT, Object.keys(out).length, 'objects', Math.round(js.length / 1024), 'KB')

/* ============================================================================
   30 Sep 2026: the Direction C set (and the red columns' process), src/assets/booth/iso-set-c-0930.js, kept apart so the
   Direction B pages do not load it.
     build   the cleanroom being built (tools/booth-cleanroom-0930.mjs), with its four leader anchors
     crane   the tower crane with a fan filter unit on its hook (same tool)
     stack   one bay of the same cleanroom, its layers lifted far apart, tall and narrow for the aisle column
     fab     the Design tab's exploded fab (fab-exploded-still), its own four labels kept; ONE red part (the cleanroom
             tray's fan filter unit): the other trays' red parts are drawn in the greys, as the booth's rule asks
     s-<k>   the six simple service objects, as drawn (icon size)
     w-<k>   the same six drawn WHITE line on field red, the red part solid white (for the red aisle columns)
   ============================================================================ */
const RED2GREY = { '#F2484B': '#FFFFFF', '#EC2326': '#E6E8EB', '#C9161B': '#C9CDD3', '#A31015': '#A9AFB8', '#A8141A': '#8E96A1', '#B8121A': '#A9AFB8' }
const REDS = new Set(['#EC2326', '#C9161B', '#F2484B', '#A31015'])
const onRed = (p, v) => (p === 'stroke' ? '#FFFFFF' : REDS.has(v.toUpperCase()) ? '#FFFFFF' : '#C8161D')
const outC = {}
for (const k of ['build', 'crane', 'stack']) {
  const o = conv(k, fs.readFileSync(`src/assets/booth/iso-c/${k === 'build' ? 'cleanroom-build' : k}.svg`, 'utf8'))
  const j = JSON.parse(fs.readFileSync(`src/assets/booth/iso-c/${k === 'build' ? 'cleanroom-build' : k}.json`, 'utf8'))
  outC[k] = { ...o, anchors: j.anchors }
}
{
  /* the fab: the red classes used inside trays t1, t2 and t4 get grey twins */
  let s = fs.readFileSync(`${SRC}/fab-exploded-still.svg`, 'utf8')
  const css = (s.match(/<style>([^<]*)<\/style>/) || [, ''])[1]
  const twins = []
  const cls = {}
  for (const [, sel, body] of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) if (sel.trim().startsWith('.')) cls[sel.trim().slice(1)] = body
  const redCls = Object.keys(cls).filter(c => /#(EC2326|C9161B|F2484B|A31015|A8141A|B8121A)/i.test(cls[c]))
  for (const c of redCls) twins.push(`.${c}g{${cls[c].replace(/#(EC2326|C9161B|F2484B|A31015|A8141A|B8121A)/gi, m => RED2GREY[m.toUpperCase()])}}`)
  s = s.replace('</style>', twins.join('') + '</style>')
  s = s.replace(/<g class="t([124])">([\s\S]*?)<\/g>/g, (m, t, body) => body.includes('class="ld"') ? m : `<g class="t${t}">${body.replace(/class="([a-z]+)"/g, (mm, c) => (redCls.includes(c) ? `class="${c}g"` : mm))}</g>`)
  outC.fab = conv('fab', s)
}
for (const k of ['design', 'procure', 'construct', 'commission', 'maintain', 'hookup']) {
  const s = fs.readFileSync(`${SRC}/svc-${k}-simple-still.svg`, 'utf8')
  outC['s-' + k] = conv('s-' + k, s)
  outC['w-' + k] = conv('w-' + k, s, onRed)
}
/* 30 Sep, evening (Bazil on the red trifold cover: "better visual and no weird white"): the complete cleanroom and the
   Design tab's cleanroom as WHITE line drawings for field red grounds: every stroke white, the faces two light tints of the
   red and the red itself (never grey or white slabs), the one accent part solid white (red on red would disappear) */
const LINE_ON_RED = { '#FFFFFF': '#D5454A', '#E6E8EB': '#CD2B31', '#C9CDD3': '#C8161D', '#A9AFB8': '#BA1219' }
const lineOnRed = (p, v) => (p === 'stroke' ? '#FFFFFF' : REDS.has(v.toUpperCase()) ? '#FFFFFF' : (LINE_ON_RED[v.toUpperCase()] || '#C8161D'))
outC['build-w'] = { ...conv('build-w', fs.readFileSync('src/assets/booth/iso-c/cleanroom-build.svg', 'utf8'), lineOnRed), anchors: outC.build.anchors }
outC['cleanroom-w'] = conv('cleanroom-w', fs.readFileSync(`${SRC}/cleanroom.svg`, 'utf8'), lineOnRed)
const OUTC = 'src/assets/booth/iso-set-c-0930.js'
const jsC = `/* generated by tools/booth-iso-0929.mjs (30 Sep 2026): the Direction C drawings and the red columns' process objects,
   classes prefixed, strokes scaled with the piece. Do not edit by hand: rerun tools/booth-cleanroom-0930.mjs, then the tool. */
export const ISO_C = ${JSON.stringify(outC)}\n`
fs.writeFileSync(OUTC, jsC)
console.log(OUTC, Object.keys(outC).length, 'objects', Math.round(jsC.length / 1024), 'KB')

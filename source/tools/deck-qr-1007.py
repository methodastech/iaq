"""7 Oct 2026: the QR codes on the deck's Scan slide (Bazil: "have a tab for qr code, for website, qr code for the form,
put temporary"). Writes src/data/deckQr.js: one entry per code as an SVG path of unit squares, the way boothQr.js is.
Re-run after the URL changes:  python3 tools/deck-qr-1007.py
The live domain is iaqtechnology.com.my (the newsroom scrape's 21,000 references); the form lives at /prospect on
whichever host this build is deployed to, so change FORM below when that is decided."""
import qrcode, json, pathlib
SITE = 'https://iaqtechnology.com.my'
FORM = 'https://iaqtechnology.com.my/prospect'
CODES = [('site', SITE, 'The website', 'iaqtechnology.com.my'), ('form', FORM, 'Leave your details', 'iaqtechnology.com.my/prospect')]
out = ["/* GENERATED by tools/deck-qr-1007.py, do not edit: the QR codes on the deck's Scan slide */", "export const DECK_QR = {"]
for k, url, label, show in CODES:
    q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=1, border=0)
    q.add_data(url); q.make(fit=True)
    m = q.get_matrix(); n = len(m)
    path = ''.join(f'M{x},{y}h1v1h-1z' for y, row in enumerate(m) for x, v in enumerate(row) if v)
    out.append(f"  {k}: {{ url: {json.dumps(url)}, label: {json.dumps(label)}, show: {json.dumps(show)}, viewBox: '0 0 {n} {n}', path: {json.dumps(path)} }},")
    print(k, url, f'{n}x{n}')
out.append('}'); out.append('')
pathlib.Path('src/data/deckQr.js').write_text('\n'.join(out))
